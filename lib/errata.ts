export type Severity = "critical" | "major" | "minor";

export interface Erratum {
  /** стабільний ідентифікатор запису */
  id: string;
  /** id задачі з `lib/tasks.ts` */
  taskId: string;
  kind: ErratumKind;
  severity: Severity;
  /** коротка назва неточності */
  title: string;
  /** як надруковано в методичці */
  printed: string;
  /** як правильно / пропозиція виправлення */
  correct: string;
  /** як виявлено, чим перевірено */
  why: string;
  /** що станеться, якщо виконувати дослівно */
  impact: string;
  /** простими словами: чому це важливо (режим «Просто») */
  simple: string;
  /** де в науковій роботі */
  where: string;
}

