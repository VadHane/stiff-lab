/** Усі специфікації сторінки задачі; перша — основна. Порожній масив для невідомого taskId. */
export function specsForTask(taskId: string): ProblemSpec[] {
  return TASK_SPECS.filter((s) => s.taskId === taskId);
}

/** Специфікація за id (`"t12-ic2"`) або undefined. */
export function specById(id: string): ProblemSpec | undefined {
  return TASK_SPECS.find((s) => s.id === id);
}

/** Повна назва для заголовків: «Хімічна кінетика Робертсона — друга початкова умова». */
export function specTitle(spec: ProblemSpec): string {
  return spec.variant ? `${spec.title} — ${spec.variant}` : spec.title;
}
